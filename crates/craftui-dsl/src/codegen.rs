fn expr_to_font_weight(expr: &Expr, ctx: &EmitCtx<'_>, tracked: bool) -> String {
    let cap_ctx = EmitCtx {
        use_self: false,
        ..*ctx
    };
    let eval_ctx = if tracked { &cap_ctx } else { ctx };
    match expr {
        Expr::Ident(s) => match s.as_str() {
            "Thin" => "100.0".into(),
            "ExtraLight" => "200.0".into(),
            "Light" => "300.0".into(),
            "Normal" | "Regular" => "400.0".into(),
            "Medium" => "500.0".into(),
            "SemiBold" | "Semibold" => "600.0".into(),
            "Bold" => "700.0".into(),
            "ExtraBold" => "800.0".into(),
            "Black" => "900.0".into(),
            _ => expr_to_f32(expr, eval_ctx, tracked),
        },
        Expr::Ternary {
            cond,
            then_expr,
            else_expr,
        } => {
            let c = expr_to_typed_rust_inner(cond, "bool", eval_ctx, tracked);
            let t = expr_to_font_weight(then_expr, eval_ctx, tracked);
            let e = expr_to_font_weight(else_expr, eval_ctx, tracked);
            format!("(if {c} {{ {t} }} else {{ {e} }})")
        }
        other => expr_to_f32(other, eval_ctx, tracked),
    }
}

fn expr_to_f32(expr: &Expr, ctx: &EmitCtx<'_>, tracked: bool) -> String {
    let cap_ctx = EmitCtx {
        use_self: false,
        ..*ctx
    };
    let eval_ctx = if tracked { &cap_ctx } else { ctx };
    match expr {
        Expr::Length(v, _) | Expr::DurationSec(v) => format!("{v}f32"),
        Expr::Float(v) => format!("{v}f32"),
        Expr::Int(v) => format!("{v}.0f32"),
        Expr::Ternary {
            cond,
            then_expr,
            else_expr,
        } => {
            let c = expr_to_typed_rust_inner(cond, "bool", eval_ctx, tracked);
            let t = expr_to_f32(then_expr, eval_ctx, tracked);
            let e = expr_to_f32(else_expr, eval_ctx, tracked);
            format!("(if {c} {{ {t} }} else {{ {e} }})")
        }
        other => {
            if tracked {
                expr_to_typed_rust_captured(other, "f32", eval_ctx)
            } else {
                expr_to_typed_rust(other, "f32", eval_ctx)
            }
        }
    }
}

fn expr_to_len(expr: &Expr, ctx: &EmitCtx<'_>, tracked: bool) -> String {
    let cap_ctx = EmitCtx {
        use_self: false,
        ..*ctx
    };
    let eval_ctx = if tracked { &cap_ctx } else { ctx };
    match expr {
        Expr::Length(v, Unit::Dp) => format!("Length::Dp({v:.2})"),
        Expr::Length(v, Unit::Px) => format!("Length::Px({v:.2})"),
        Expr::Length(v, Unit::Pct) => format!("Length::Pct({v:.2})"),
        Expr::Length(v, Unit::Deg | Unit::Rad) => format!("Length::Dp({v:.2})"),
        Expr::Int(v) => format!("Length::Dp({v}.0)"),
        Expr::Float(v) => format!("Length::Dp({v:.2})"),
        Expr::Ident(s) if s == "Auto" => "Length::Auto".into(),
        Expr::Ternary {
            cond,
            then_expr,
            else_expr,
        } => {
            let c = expr_to_typed_rust_inner(cond, "bool", eval_ctx, tracked);
            let t = expr_to_len(then_expr, eval_ctx, tracked);
            let e = expr_to_len(else_expr, eval_ctx, tracked);
            format!("(if {c} {{ {t} }} else {{ {e} }})")
        }
        other => format!("Length::Dp({})", expr_to_f32(other, eval_ctx, tracked)),
    }
}

/// `build.rs` helper: resolve imports and compile a single `.cui` file into `OUT_DIR/<stem>.rs`.
pub fn compile_cui_file(
    cui_path: impl AsRef<Path>,
    out_rs: impl AsRef<Path>,
) -> std::io::Result<()> {
    let resolved = resolve_file(cui_path.as_ref());
    if let Some(err) = resolved
        .diagnostics
        .iter()
        .find(|d| d.severity == Severity::Error)
    {
        return Err(std::io::Error::new(
            std::io::ErrorKind::InvalidData,
            format!("{}: {}", cui_path.as_ref().display(), err.message),
        ));
    }
    let rust = generate_rust(&resolved.merged);
    std::fs::write(out_rs.as_ref(), rust)
}

/// `build.rs` helper: resolve & compile all `.cui` files in `dir` into `out_dir`.
pub fn compile_cui_dir(dir: impl AsRef<Path>, out_dir: impl AsRef<Path>) -> std::io::Result<()> {
    std::fs::create_dir_all(out_dir.as_ref())?;
    for entry in std::fs::read_dir(dir.as_ref())? {
        let entry = entry?;
        let path = entry.path();
        if path.extension().and_then(|e| e.to_str()) == Some("cui") {
            let stem = path.file_stem().and_then(|s| s.to_str()).unwrap_or("ui");
            let out_rs = out_dir.as_ref().join(format!("{stem}.rs"));
            compile_cui_file(&path, &out_rs)?;
        }
    }
    Ok(())
}

