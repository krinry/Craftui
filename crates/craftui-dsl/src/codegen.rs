fn expr_is_theme_color(expr: &Expr) -> bool {
    match expr {
        Expr::Member(base, field) => {
            matches!(base.as_ref(), Expr::Ident(s) if s == "Theme")
                && !matches!(
                    field.as_str(),
                    "radius_md"
                        | "spacing_unit"
                        | "spacing_xs"
                        | "spacing_sm"
                        | "spacing_md"
                        | "spacing_lg"
                        | "spacing_xl"
                        | "spacing_xxl"
                        | "mode"
                )
        }
        Expr::Ternary {
            then_expr,
            else_expr,
            ..
        } => expr_is_theme_color(then_expr) || expr_is_theme_color(else_expr),
        _ => false,
    }
}

