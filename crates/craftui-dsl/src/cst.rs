pub type SyntaxNode = rowan::SyntaxNode<CuiLanguage>;
pub type SyntaxToken = rowan::SyntaxToken<CuiLanguage>;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn syntax_kind_round_trip_table_matches_enum_discriminants() {
        for k in [
            SyntaxKind::Slash,
            SyntaxKind::Question,
            SyntaxKind::ColorHex,
            SyntaxKind::Duration,
            SyntaxKind::Ident,
            SyntaxKind::AnimateBlock,
            SyntaxKind::ExprNode,
            SyntaxKind::ErrorNode,
        ] {
            let raw: rowan::SyntaxKind = k.into();
            assert_eq!(CuiLanguage::kind_from_raw(raw), k);
        }
    }
}
